// Pulls the live replica-lab results from https://revers.si/data/results.json and writes
// scripts/promo/data.js, the only source of numbers in the promo's agent-tile scene.
//   node scripts/promo/build-data.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const URL = 'https://revers.si/data/results.json';
const res = await fetch(URL);
if (!res.ok) throw new Error(`${URL}: HTTP ${res.status}`);
const r = await res.json();

const taskOrder = ['buy-gme-100', 'value-portfolio'];
const order = ['naive-search', 'registry-only', 'oracle-blind', 'revers-guarded']; // worst to best by avgScore
const lb = new Map(r.leaderboard.map((l) => [l.agentId, l]));
const agents = r.agents
  .filter((a) => lb.has(a.id))
  .sort((a, b) => lb.get(a.id).avgScore - lb.get(b.id).avgScore || order.indexOf(a.id) - order.indexOf(b.id))
  .map((a) => {
    const runs = taskOrder.flatMap((t) =>
      r.scenarios
        .map((s) => r.runs.find((x) => x.agentId === a.id && x.scenarioId === s.id && x.taskId === t))
        .filter(Boolean)
        .map((x) => ({ scenario: x.scenarioId, task: x.taskId, verdict: x.verdict, score: x.score })),
    );
    const l = lb.get(a.id);
    return { id: a.id, name: a.name, kind: a.kind, avgScore: l.avgScore, failures: l.failures, runs: l.runs, passRate: l.passRate, cells: runs };
  });

const skipped = r.agents.filter((a) => a.status === 'skipped').map((a) => ({ id: a.id, name: a.name, model: a.model ?? null }));
const data = {
  source: URL,
  fetchedAt: new Date().toISOString(),
  generatedAt: r.generatedAt,
  mode: r.mode,
  chain: r.chain,
  scenarios: r.scenarios.length,
  totalRuns: r.runs.length,
  prompt: r.tasks.find((t) => t.id === 'buy-gme-100')?.prompt,
  agents,
  skipped,
};
const out = join(dirname(fileURLToPath(import.meta.url)), 'data.js');
writeFileSync(out, `// Generated by build-data.mjs from ${URL}. Do not edit by hand.\nwindow.PROMO_DATA = ${JSON.stringify(data, null, 2)};\n`);
console.log('wrote', out);
for (const a of agents) console.log(a.id.padEnd(16), String(a.avgScore).padStart(5), `${a.failures}/${a.runs} failed`, a.cells.map((c) => c.verdict[0]).join(''));
console.log('skipped:', skipped.map((s) => s.id).join(', ') || 'none');
